"""User-facing runtime errors. The CLI catches MacawError and prints cleanly."""


class MacawError(Exception): ...


# input / project layout
class InputNotFoundError(MacawError): ...
class UnreadableMediaError(MacawError): ...
class RecordingNotFoundError(MacawError): ...


# configuration
class ConfigError(MacawError): ...
class UnknownConfigKeyError(ConfigError): ...
class ConfigValidationError(ConfigError): ...


# store
class SchemaViolationError(MacawError): ...
class CacheCorruptError(MacawError): ...


# extractors / backends
class ExtractorNotFoundError(MacawError): ...
class BackendNotAvailableError(MacawError): ...
class ExternalToolError(MacawError): ...
class ExtractionFailedError(MacawError): ...


# quality control
class QCFailure(MacawError): ...
class AlignmentFailedError(QCFailure): ...
class TranscriptMismatchError(QCFailure): ...
class TrackRepairFailedError(QCFailure): ...


# coding
class CodebookError(MacawError): ...
class LLMBackendError(MacawError): ...
class LLMResponseParseError(MacawError): ...


# interop
class EafError(MacawError): ...


# execution
class JobSubmissionError(MacawError): ...
class DependencyCycleError(MacawError): ...
class TaskFailedError(MacawError): ...
